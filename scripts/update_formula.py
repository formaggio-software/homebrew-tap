#!/usr/bin/env python3
"""Generate a Homebrew binary formula using real local release archives.

Example:
  python3 scripts/update_formula.py v1.2.3 --assets-dir dist
"""

import argparse
import hashlib
import re
import runpy
import tarfile
from pathlib import Path

PACKAGE = "rhtop"
PLATFORMS = ("darwin-universal2", "linux-arm64", "linux-amd64")
ROOT = Path(__file__).resolve().parents[1]
MACHO = runpy.run_path(str(Path(__file__).resolve().with_name("macho.py")))


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def assert_contains_binary(archive: Path, platform: str) -> None:
    if platform not in PLATFORMS:
        raise SystemExit(f"ERROR: unsupported archive platform: {platform}")
    with tarfile.open(archive, "r:gz") as tf:
        members = tf.getmembers()
        names = [member.name for member in members]
        if len(names) != len(set(names)):
            raise SystemExit(f"ERROR: duplicate archive members: {archive.name}")
        for member in members:
            parts = Path(member.name).parts
            if (
                member.name.startswith("/")
                or ".." in parts
                or not (member.isfile() or member.isdir())
                or not parts
                or parts[0] not in (PACKAGE, "NOTICE", "LICENSE.txt", "THIRD_PARTY_NOTICES")
            ):
                raise SystemExit(f"ERROR: unexpected archive member: {member.name}")
        for required in (PACKAGE, "NOTICE", "LICENSE.txt"):
            if required not in names or not tf.getmember(required).isfile():
                raise SystemExit(f"ERROR: missing {required}: {archive.name}")
        if not any(name.startswith("THIRD_PARTY_NOTICES/") for name in names):
            raise SystemExit(f"ERROR: missing third-party notices: {archive.name}")
        binary = tf.getmember(PACKAGE)
        if not binary.mode & 0o111:
            raise SystemExit(f"ERROR: binary is not executable: {archive.name}")
        with tf.extractfile(binary) as stream:
            header = stream.read(20)
            if platform.startswith("darwin-"):
                try:
                    valid = MACHO["architectures"](stream) == {"x86_64", "arm64"}
                except ValueError as exc:
                    raise SystemExit(f"ERROR: {archive.name}: {exc}") from None
        os_name, arch = platform.split("-", 1)
        if os_name == "linux":
            valid = (
                header[:6] == b"\x7fELF\x02\x01"
                and int.from_bytes(header[18:20], "little") == {"amd64": 62, "arm64": 183}[arch]
            )
        if not valid:
            raise SystemExit(f"ERROR: binary does not match {platform}: {archive.name}")


def platform_block(os_name: str, arch: str, asset_url: str, checksum: str) -> str:
    return (
        f"    on_{'arm' if arch == 'arm64' else 'intel'} do\n"
        f'      url "{asset_url}"\n'
        f'      sha256 "{checksum}"\n'
        "    end"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("tag", help="Version tag including v prefix, e.g. v1.2.3")
    parser.add_argument(
        "--assets-dir",
        type=Path,
        required=True,
        help="Directory holding the universal2 macOS and two Linux release archives",
    )
    parser.add_argument(
        "--github-repo",
        default="formaggio-software/rhtop",
        help="GitHub release repository, as ORG/REPO",
    )
    args = parser.parse_args()

    if not re.fullmatch(r"v[0-9]+(?:\.[0-9]+){1,3}(?:[-+][A-Za-z0-9.-]+)?", args.tag):
        parser.error("tag must look like v1.2.3")
    if not re.fullmatch(r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+", args.github_repo):
        parser.error("--github-repo must be ORG/REPO")
    if not args.assets_dir.is_dir():
        parser.error("assets directory does not exist")

    blocks = {}
    for platform in PLATFORMS:
        os_name, arch = platform.split("-", 1)
        filename = f"{PACKAGE}-{args.tag}-{platform}.tar.gz"
        archive = args.assets_dir / filename
        if not archive.is_file():
            raise SystemExit(f"ERROR: missing archive: {archive}")
        assert_contains_binary(archive, platform)
        url = f"https://github.com/{args.github_repo}/releases/download/{args.tag}/{filename}"
        checksum = sha256_file(archive)
        blocks[platform] = (
            f'    url "{url}"\n    sha256 "{checksum}"'
            if os_name == "darwin"
            else platform_block(os_name, arch, url, checksum)
        )

    formula = f"""# Generated by scripts/update_formula.py. Edit the generator, not this file.
class Rhtop < Formula
  desc "Read-only Robinhood MCP terminal dashboard"
  homepage "https://github.com/{args.github_repo}"
  version "{args.tag[1:]}"
  license :cannot_represent

  on_macos do
{blocks["darwin-universal2"]}
  end

  on_linux do
{blocks["linux-arm64"]}
{blocks["linux-amd64"]}
  end

  def install
    bin.install "{PACKAGE}"
    prefix.install "NOTICE", "LICENSE.txt", "THIRD_PARTY_NOTICES"
  end

  test do
    system "#{{bin}}/{PACKAGE}", "--version"
  end
end
"""
    output = ROOT / "Formula" / f"{PACKAGE}.rb"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(formula, encoding="utf-8")
    print(f"Wrote {output.relative_to(ROOT)} using verified archives and SHA-256 values")
    print("Ensure assets are published to the matching GitHub Release before installing.")


if __name__ == "__main__":
    main()
